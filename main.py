# PYDANTIC MODELS
# ============================================================

class AnalysisResult(BaseModel):
    """
    Represents the final result generated by the ATS analysis.

    This model defines the structure that n8n must send
    back to the FastAPI application.
    """

    # ATS score between 0 and 100
    score: int = Field(ge=0, le=100)

    # Overall classification/verdict
    verdict: str

    # Short explanation of the result
    summary: str

    # Positive aspects found in the resume
    strengths: list[str] = []

    # Missing skills, experience, or requirements
    gaps: list[str] = []

    # Suggestions for improving the resume
    recommendations: list[str] = []

    # Keywords from the job description found in the resume
    matched_keywords: list[str] = []

    # Keywords from the job description missing from the resume
    missing_keywords: list[str] = []


class AnalysisCallback(BaseModel):
    """
    Structure of the payload received from n8n
    when the analysis is completed.
    """

    # ID of the analysis that was processed
    analysis_id: UUID

    # Current status of the analysis
    status: str = "completed"

    # Actual ATS analysis result
    result: AnalysisResult


