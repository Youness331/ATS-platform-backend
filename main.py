# CREATE ANALYSIS / SEND TO N8N
# ============================================================

@app.post("/api/analyses")
async def create_analysis(
    # Job description submitted as multipart form data
    job_description: Annotated[str, Form()],

    # Resume uploaded as a file
    resume: Annotated[UploadFile, File()],
):
    """
    Create a new ATS analysis.

    The workflow is:

        User
          ↓
        FastAPI
          ↓
        Save analysis in database
          ↓
        Send resume + job description to n8n
          ↓
        n8n processes the analysis
          ↓
        n8n calls the callback endpoint
          ↓
        FastAPI stores the final result
    """

    # --------------------------------------------------------
    # Validate job description
    # --------------------------------------------------------

    if not job_description.strip():
        raise HTTPException(
            status_code=422,
            detail="job_description is required",
        )


    # --------------------------------------------------------
    # Validate resume
    # --------------------------------------------------------

    if not resume.filename:
        raise HTTPException(
            status_code=422,
            detail="resume is required",
        )


    # Only PDF resumes are accepted.
    allowed_types = {
        "application/pdf"
    }

    if resume.content_type not in allowed_types:
        raise HTTPException(
            status_code=415,
            detail="Upload a PDF resume",
        )


    # --------------------------------------------------------
    # Generate a unique ID for this analysis
    # --------------------------------------------------------

    analysis_id = uuid4()


    # Read the uploaded PDF into memory.
    resume_bytes = await resume.read()


    # --------------------------------------------------------
    # Save initial analysis record
    # --------------------------------------------------------

    # Store the analysis in the local database before
    # sending it to n8n.
    create_analysis_record(
        str(analysis_id),
        resume.filename,
        job_description,
    )


    # --------------------------------------------------------
    # Prepare data for the n8n webhook
    # --------------------------------------------------------

    # Regular form fields sent to n8n.
    form_data = {
        "analysis_id": str(analysis_id),
        "job_description": job_description,
    }


    # Uploaded PDF file sent to n8n.
    files = {
        "resume": (
            resume.filename,
            resume_bytes,
            resume.content_type
            or "application/octet-stream",
        )
    }


    # --------------------------------------------------------
    # Send the analysis request to n8n
    # --------------------------------------------------------

    try:

        # Create an asynchronous HTTP client.
        async with httpx.AsyncClient(timeout=30) as client:

            # Send the job description and resume
            # to the n8n webhook.
            response = await client.post(
                N8N_WEBHOOK_URL,
                data=form_data,
                files=files,
            )

            # Raise an exception if n8n returns an HTTP error.
            response.raise_for_status()


    except httpx.HTTPError as error:

        # If communication with n8n fails,
        # mark the analysis as failed.
        update_status(
            str(analysis_id),
            "failed",
        )

        # Return a 502 Bad Gateway because FastAPI
        # could not communicate with the external n8n service.
        raise HTTPException(
            status_code=502,
            detail="Could not queue analysis in n8n",
        ) from error


    # --------------------------------------------------------
    # Mark the analysis as processing
    # --------------------------------------------------------

    update_status(
        str(analysis_id),
        "processing",
    )


    # --------------------------------------------------------
    # Return response to frontend
    # --------------------------------------------------------

    # 202 means the request was accepted,
    # but the analysis is still being processed.
    return JSONResponse(
        status_code=202,
        content={
            "analysis_id": str(analysis_id),

            "status": "processing",

            # Frontend can use this URL to poll
            # the current analysis status.
            "status_url": f"/api/analyses/{analysis_id}",
        },
    )


