# GET A SINGLE ANALYSIS

@app.get("/api/analyses/{analysis_id}")
async def get_analysis(
    analysis_id: UUID,
):
    """
    Retrieve the current status or final result
    of a specific analysis.

    The frontend can repeatedly call this endpoint
    while the analysis is being processed.

    Example:

        processing
            ↓
        processing
            ↓
        completed + result
    """

    # Retrieve analysis from the database.
    analysis = get_analysis_record(
        str(analysis_id)
    )


    # If the ID does not exist, return 404.
    if analysis is None:
        raise HTTPException(
            status_code=404,
            detail="Analysis not found",
        )


    # Return the current analysis information.
    return analysis