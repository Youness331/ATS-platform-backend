# RECEIVE RESULT FROM N8N
# ============================================================

@app.post("/api/analyses/{analysis_id}/result")
async def receive_analysis_result(
    analysis_id: UUID,
    callback: AnalysisCallback,
):
    """
    Callback endpoint used by n8n.

    Once n8n finishes analyzing the resume,
    it sends the structured result back to this endpoint.

    Example flow:

        n8n
         ↓
        POST /api/analyses/{analysis_id}/result
         ↓
        Validate analysis
         ↓
        Save result in database
         ↓
        Return success
    """

    # --------------------------------------------------------
    # Check whether the analysis exists
    # --------------------------------------------------------

    analysis = get_analysis_record(
        str(analysis_id)
    )

    if analysis is None:
        raise HTTPException(
            status_code=404,
            detail="Analysis not found",
        )


# Make sure the callback ID matches the URL ID

    if callback.analysis_id != analysis_id:
        raise HTTPException(
            status_code=400,
            detail="analysis_id does not match callback URL",
        )


    # Save the completed analysis

    complete_analysis(
        str(analysis_id),
        callback.status,
        callback.result.model_dump(),
    )


    # Confirm that the result was successfully stored.
    return {
        "ok": True,
        "analysis_id": str(analysis_id),
        "status": callback.status,
    }


